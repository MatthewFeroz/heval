import { useState } from 'react'
import { useMutation } from 'convex/react'
import { api } from '../../convex/_generated/api'
import { MAX_IMPORT_BYTES, parseReport, type ReportData } from './format'
import { message } from './helpers'
import { reportHref } from './workspaceNavigation'

export function ImportResults() {
  const save = useMutation(api.reports.save)
  const [draft, setDraft] = useState<ReportData | null>(null), [title, setTitle] = useState(''), [error, setError] = useState(''), [busy, setBusy] = useState(false)
  async function choose(file: File | undefined) {
    if (!file) return
    setError(''); setDraft(null)
    try {
      if (file.size > MAX_IMPORT_BYTES) throw new Error('Use a JSON export smaller than 750 KB.')
      const next = parseReport(await file.text()); setDraft(next); setTitle(next.job.slice(0, 120))
    } catch (e) { setError(message(e)) }
  }
  async function persist() {
    if (!draft) return
    setBusy(true); setError('')
    try { const id = await save({ json: JSON.stringify(draft), title }); location.assign(reportHref(id)) }
    catch (e) { setError(message(e)); setBusy(false) }
  }
  return <section className="report-card report-import" aria-label="Import results"><h2>Import evaluation results</h2><p>Choose a normalized Harbor JSON export up to 750 KB. It opens in the same workspace as a comparison run here.</p>
    <label className="report-file">Choose Harbor JSON<input aria-label="Choose Harbor JSON" type="file" accept=".json,application/json" disabled={busy} onChange={event => void choose(event.target.files?.[0])} /></label>
    <details><summary>Where do I get this file?</summary><p>Use the normalized <code>results/harbor/&lt;job&gt;.json</code> generated by OpenEval's Harbor report exporter. Raw Harbor result.json files and Studio bundles must be exported as normalized Harbor JSON first.</p><p>Run <code>bun run report path/to/harbor-job</code> in a OpenEval checkout. The CLI can inspect the export with <code>heval open path/to/export.json</code>.</p></details>
    <p>Have a saved project or bundle with multiple sources? <a href="/studio">Open a project or bundle</a> to keep its analysis and presentation settings.</p>
    {draft && <div className="report-import-preview"><h3>Review before saving</h3><p>{draft.rows.length} trials · {new Set(draft.rows.map(row => row.model)).size} models · {new Set(draft.rows.map(row => row.task)).size} tasks</p><label>Report title<input maxLength={120} value={title} onChange={event => setTitle(event.target.value)} /></label><p>Only trial labels, outcomes, timings, token counts, costs and provenance fields shown below are saved. Check labels for sensitive information before sharing.</p><details><summary>Review exact saved data</summary><pre>{JSON.stringify(draft, null, 2)}</pre></details><button className="primary" disabled={busy || !title.trim()} onClick={() => void persist()}>{busy ? 'Saving report…' : 'Save private report'}</button><button className="secondary" disabled={busy} onClick={() => setDraft(null)}>Cancel</button></div>}
    {error && <p role="alert">{error}</p>}
  </section>
}
